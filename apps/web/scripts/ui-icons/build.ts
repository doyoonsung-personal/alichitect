// Turns the UI icon drafts (apps/web/.qwen/icons.json: name -> SVG child elements, drafted by qwen3.8-max from a written
// spec) into src/shell/ui-icons.generated.ts. The drafts are untrusted text: every element and attribute is checked
// against an allowlist, the shared stroke attributes are dropped (the Icon component sets them once), and a draft that
// leaves the 16 px grid or breaks a rule fails the build.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(HERE, '../../.qwen/icons.json');
const OUT = path.resolve(HERE, '../../src/shell/ui-icons.generated.ts');

const ELEMENTS = new Set(['path', 'line', 'polyline', 'rect', 'circle']);
const SHARED: Record<string, string> = { fill: 'none', stroke: 'currentColor', 'stroke-width': '1.5', 'stroke-linecap': 'square', 'stroke-linejoin': 'miter' };
const GEOMETRY = new Set(['d', 'x1', 'y1', 'x2', 'y2', 'points', 'x', 'y', 'width', 'height', 'rx', 'ry', 'cx', 'cy', 'r', 'stroke-dasharray']);
const VALUE = /^[0-9a-zA-Z .,\-+]+$/;

type Node = { el: string; a: Record<string, string> };

export function parseIcon(name: string, markup: string): Node[] {
  const out: Node[] = [];
  const re = /<(\w+)\s+([^<>]*?)\s*\/>/g;
  let consumed = 0;
  for (const m of markup.matchAll(re)) {
    consumed += m[0].length;
    const el = m[1];
    if (!ELEMENTS.has(el)) throw new Error(`${name}: element <${el}> is not allowed`);
    const a: Record<string, string> = {};
    for (const at of m[2].matchAll(/([\w-]+)="([^"]*)"/g)) {
      const [, k, v] = at;
      if (Object.hasOwn(SHARED, k)) {
        if (SHARED[k] !== v) throw new Error(`${name}: ${k}="${v}" differs from the shared ${k}="${SHARED[k]}"`);
        continue;
      }
      if (!GEOMETRY.has(k)) throw new Error(`${name}: attribute ${k} is not allowed`);
      if (!VALUE.test(v)) throw new Error(`${name}: value of ${k} has unexpected characters`);
      a[k] = v;
    }
    out.push({ el, a });
  }
  if (consumed < markup.replace(/\s+/g, '').length * 0.5 || !out.length) throw new Error(`${name}: markup was not fully understood`);
  if (out.length > 6) throw new Error(`${name}: more than 6 elements`);
  // every number must sit on the 16 px grid, inside the 1.5..14.5 live area
  for (const n of out) {
    for (const [k, v] of Object.entries(n.a)) {
      if (k === 'stroke-dasharray' || k === 'd') continue; // path data holds arc flags and radii; the contact sheet is the check for paths
      for (const num of v.match(/-?\d*\.?\d+/g) ?? []) {
        const x = Number(num);
        if (k === 'width' || k === 'height' || k === 'r' || k === 'rx' || k === 'ry') continue;
        if (x < 1.4 || x > 14.6) throw new Error(`${name}: ${k} has ${x}, outside the 1.5 to 14.5 live area`);
      }
    }
  }
  return out;
}

function main(): void {
  const src = JSON.parse(readFileSync(SRC, 'utf8')) as Record<string, string>;
  const icons: Record<string, Node[]> = {};
  for (const [name, markup] of Object.entries(src)) icons[name] = parseIcon(name, markup);
  const names = Object.keys(icons);
  const body = names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(icons[n])},`).join('\n');
  writeFileSync(
    OUT,
    `// GENERATED by apps/web/scripts/ui-icons/build.ts from .qwen/icons.json (drafted by qwen3.8-max, checked and fixed by hand). Do not edit.\n// 16 px grid, drawn with fill none, stroke currentColor, 1.5 px, square caps and mitred joins (set once on the <svg>).\n\nexport type UiIconName = ${names.map((n) => JSON.stringify(n)).join(' | ')};\nexport interface UiIconNode {\n  el: 'path' | 'line' | 'polyline' | 'rect' | 'circle';\n  a: Readonly<Record<string, string>>;\n}\n\nexport const UI_ICONS: Readonly<Record<UiIconName, readonly UiIconNode[]>> = {\n${body}\n};\n`,
  );
  process.stdout.write(`wrote ${names.length} icons\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
