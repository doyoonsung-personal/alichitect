// Copies the app's design tokens (apps/web/src/styles/tokens.css, both themes) and its pre-paint theme script
// (apps/web/public/theme.js) into src/pages/tokens.ts, so the sign-in, pending, account and admin pages use the same
// variables as the SPA and follow the same stored theme. test/pages.test.ts fails when the copy is out of date.
//   node scripts/sync-tokens.ts        (npm run sync:tokens)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const SOURCE = fileURLToPath(new URL('../../web/src/styles/tokens.css', import.meta.url));
export const THEME_SOURCE = fileURLToPath(new URL('../../web/public/theme.js', import.meta.url));
export const TARGET = fileURLToPath(new URL('../src/pages/tokens.ts', import.meta.url));

const lf = (s: string): string => s.replace(/\r\n/g, '\n');

export function render(css: string, themeJs: string): string {
  return `// GENERATED by scripts/sync-tokens.ts from apps/web/src/styles/tokens.css and apps/web/public/theme.js. Do not edit; run npm run sync:tokens.\nexport const TOKENS_CSS = ${JSON.stringify(lf(css))};\nexport const THEME_JS = ${JSON.stringify(lf(themeJs))};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(TARGET, render(readFileSync(SOURCE, 'utf8'), readFileSync(THEME_SOURCE, 'utf8')));
  console.log(`wrote ${TARGET}`);
}
