// Copies the app's design tokens (apps/web/src/styles/tokens.css) into src/pages/tokens.ts, so the sign-in, pending
// and admin pages use the same variables as the SPA. test/pages.test.ts fails when the copy is out of date.
//   node scripts/sync-tokens.ts        (npm run sync:tokens)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const SOURCE = fileURLToPath(new URL('../../web/src/styles/tokens.css', import.meta.url));
export const TARGET = fileURLToPath(new URL('../src/pages/tokens.ts', import.meta.url));

export function render(css: string): string {
  return `// GENERATED by scripts/sync-tokens.ts from apps/web/src/styles/tokens.css. Do not edit; run npm run sync:tokens.\nexport const TOKENS_CSS = ${JSON.stringify(css.replace(/\r\n/g, '\n'))};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(TARGET, render(readFileSync(SOURCE, 'utf8')));
  console.log(`wrote ${TARGET}`);
}
